def seed_master(conn: sqlite3.Connection) -> None:
    conn.executemany(
        "INSERT OR IGNORE INTO spots(id,name,area,svg_key,description,access,best_season,map_x,map_y) VALUES(?,?,?,?,?,?,?,?,?)",
        SPOTS,
    )
    conn.executemany(
        "INSERT OR IGNORE INTO shops(id,spot_id,name,area,category,open_time,close_time,closed_weekday,rate_percent,is_unmanned,svg_key,description,access,best_season) "
        "VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
        SHOPS,
    )
    conn.executemany("INSERT OR IGNORE INTO people(id,shop_id,name,intro,svg_key) VALUES(?,?,?,?,?)", PEOPLE)
    conn.executemany(
        "INSERT OR IGNORE INTO promises(id,person_id,season,title,note,start_md,end_md) VALUES(?,?,?,?,?,?,?)", PROMISES
    )
    conn.executemany(
        "INSERT OR IGNORE INTO prizes(id,category,name,face_value,weight,stock,enabled) VALUES(?,?,?,?,?,?,?)", PRIZES
    )
    if conn.execute("SELECT COUNT(*) AS c FROM voices").fetchone()["c"] == 0:
        conn.executemany(
            "INSERT INTO voices(target_type,target_id,season,author,text,hashtags) VALUES(?,?,?,?,?,?)", VOICES
        )
    # 主人公
    conn.execute(
        "INSERT OR IGNORE INTO users(id,name,source) VALUES(?,?,?)",
        (8800001, "test_traveler_0001", "seed"),
    )
